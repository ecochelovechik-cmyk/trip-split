/* window.T(key, vars) — подстановка {переменных}, запасной вариант: ru, затем сам ключ. */

/* Множественное число. Русский: 1 трата / 2 траты / 5 трат; английский: 1 expense / N expenses;
   узбекский форм не меняет. Ищет ключи вида "<key>.one|.few|.many", иначе откатывается на сам ключ. */
window.TP = function(key, n){
  var lang = "ru";
  try{ lang = localStorage.getItem("ts.lang") || "ru"; }catch(e){}
  var form;
  if(lang === "ru"){
    var mod10 = n % 10, mod100 = n % 100;
    if(mod10 === 1 && mod100 !== 11) form = "one";
    else if(mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) form = "few";
    else form = "many";
  } else if(lang === "en"){
    form = (n === 1) ? "one" : "many";
  } else {
    form = "many";
  }
  var dict = window.I18N[lang] || {};
  var withForm = key + "." + form;
  if(dict[withForm] != null || (window.I18N.ru || {})[withForm] != null) return window.T(withForm, {n:n});
  return window.T(key, {n:n});
};

window.T = function(key, vars){
  var lang = "ru";
  try{ lang = localStorage.getItem("ts.lang") || "ru"; }catch(e){}
  var dict = window.I18N[lang] || {};
  var s = dict[key];
  if(s == null) s = (window.I18N.ru || {})[key];
  if(s == null) s = key;
  if(vars){
    s = s.replace(/\{(\w+)\}/g, function(m, k){
      return (vars[k] !== undefined && vars[k] !== null) ? String(vars[k]) : m;
    });
  }
  return s;
};
